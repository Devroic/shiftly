import { eq, sql } from 'drizzle-orm';
import { useCallback } from 'react';

import { db } from '@/src/db';
import { shifts } from '@/src/db/schema';

import type { ShiftType } from '../types';

/** Returns a function that sets (or clears, when `type` is null) the shift for a given date. */
export function useUpsertShift() {
  return useCallback(async (date: string, type: ShiftType | null): Promise<void> => {
    if (type === null) {
      await db.delete(shifts).where(eq(shifts.date, date));
      return;
    }

    await db
      .insert(shifts)
      .values({ date, type })
      .onConflictDoUpdate({
        target: shifts.date,
        // A manual edit is no longer "generated by" any pattern.
        set: { type, sourcePatternId: null, updatedAt: sql`(current_timestamp)` },
      });
  }, []);
}
